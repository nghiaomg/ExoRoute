// Generates scoped Svelte stylesheets from the static sketch design system.
//
//   node sketch/build-css.mjs
//
// - parts/head.html <style> block  -> web/src/styles/dashboard/base.css
//     every selector prefixed with `.dashboard-app`
// - pages/<id>.css                 -> web/src/styles/dashboard/pages/<id>.css
//     every selector prefixed with `.dashboard-app.dashboard-page-<id>`
//
// Scoping keeps the sketch class names (.icon, .field, .status, .modal …)
// from leaking into the rest of the dashboard. `:root`/`html`/`body` rules are
// remapped onto `.dashboard-app` so CSS variables and base typography apply to the
// shell root element instead of the document.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../web/package.json', import.meta.url));
const postcss = require('postcss');

const here = dirname(fileURLToPath(import.meta.url));
const webStyles = join(here, '..', 'web', 'src', 'styles', 'dashboard');
mkdirSync(join(webStyles, 'pages'), { recursive: true });

const PAGE_IDS = ['apikeys', 'chat', 'combos', 'docs', 'help', 'overview', 'providers', 'quota', 'requests', 'settings'];

function splitSelectors(selector) {
  const parts = [];
  let depth = 0;
  let current = '';
  for (const ch of selector) {
    if (ch === '(' || ch === '[' || ch === '{') depth += 1;
    if (ch === ')' || ch === ']' || ch === '}') depth -= 1;
    if (ch === ',' && depth === 0) {
      parts.push(current);
      current = '';
    } else {
      current += ch;
    }
  }
  if (current.trim()) parts.push(current);
  return parts;
}

const ROOTISH = new Set([':root', 'html', 'body', 'html body', 'body *']);

function scopeSelector(raw, prefix) {
  return splitSelectors(raw)
    .map((sel) => {
      const s = sel.trim();
      if (!s) return s;
      const key = s.replace(/\s+/g, ' ').toLowerCase();
      if (ROOTISH.has(key) || key === ':root') return prefix.trim();
      if (key.startsWith('body ') || key === 'body') return `${prefix.trim()} ${s.replace(/^body\s*/, '')}`.trim();
      return `${prefix.trim()} ${s}`;
    })
    .join(',\n  ');
}

function scopeCss(css, prefix) {
  const root = postcss.parse(css);
  root.walkRules((rule) => {
    // Skip @keyframes inner rules (from/to/%) — they are not selectors.
    let p = rule.parent;
    let inKeyframes = false;
    while (p) {
      if (p.type === 'atrule' && /keyframes$/i.test(p.name)) { inKeyframes = true; break; }
      p = p.parent;
    }
    if (inKeyframes) return;
    rule.selector = scopeSelector(rule.selector, prefix);
  });
  return root.toString();
}

// ── base.css from parts/head.html ──────────────────────────────────────────
const head = readFileSync(join(here, 'parts', 'head.html'), 'utf8');
const styleMatches = [...head.matchAll(/<style>([\s\S]*?)<\/style>/g)];
if (styleMatches.length === 0) throw new Error('no <style> block found in parts/head.html');
// head.html carries the design system in one block plus a second block for the
// responsive/drawer/hover layer; merge them in document order.
const baseCss = scopeCss(
  styleMatches.map((m) => m[1]).join('\n'),
  '.dashboard-app',
);
writeFileSync(
  join(webStyles, 'base.css'),
  `/* GENERATED by sketch/build-css.mjs — do not edit. Source: sketch/parts/head.html */\n${baseCss}\n`,
);
console.log(`wrote base.css (${baseCss.length} chars)`);

// ── per-page css ───────────────────────────────────────────────────────────
for (const id of PAGE_IDS) {
  const css = readFileSync(join(here, 'pages', `${id}.css`), 'utf8');
  const scoped = scopeCss(css, `.dashboard-app.dashboard-page-${id}`);
  writeFileSync(
    join(webStyles, 'pages', `${id}.css`),
    `/* GENERATED by sketch/build-css.mjs — do not edit. Source: sketch/pages/${id}.css */\n${scoped}\n`,
  );
  console.log(`wrote pages/${id}.css`);
}

const activePageFiles = new Set(PAGE_IDS.map((id) => `${id}.css`));
for (const filename of readdirSync(join(webStyles, 'pages'))) {
  if (!filename.endsWith('.css') || activePageFiles.has(filename)) continue;
  const file = join(webStyles, 'pages', filename);
  const contents = readFileSync(file, 'utf8');
  if (contents.startsWith('/* GENERATED by sketch/build-css.mjs')) unlinkSync(file);
}
